import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {chromium} from 'playwright';

const env=Object.fromEntries((await readFile('../.env','utf8')).split('\n').filter(line=>/^[A-Z_]+=/.test(line)).map(line=>{const i=line.indexOf('=');return [line.slice(0,i),line.slice(i+1)];}));
const browser=await chromium.launch(process.env.E2E_CHROMIUM_EXECUTABLE?{executablePath:process.env.E2E_CHROMIUM_EXECUTABLE}:{});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const output=process.env.E2E_OUTPUT_DIR??'../backend/var/e2e';
await mkdir(output,{recursive:true});
try {
  await page.goto(process.env.E2E_BASE_URL??env.APP_ORIGIN);
  await page.getByRole('button',{name:'Войти',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:resolve(output,'login-warm.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  const password=page.getByLabel('Пароль',{exact:true});
  assert.equal(await password.getAttribute('type'),'password');
  await password.fill('demo-only 007 ');
  await page.getByRole('button',{name:'Показать пароль',exact:true}).click({timeout:5000});
  await page.getByRole('button',{name:'Скрыть пароль',exact:true}).waitFor();
  assert.equal(await password.getAttribute('type'),'text');
  assert.equal(await password.inputValue(),'demo-only 007 ');
  assert.equal(await page.getByRole('button',{name:'Скрыть пароль',exact:true}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:'Скрыть пароль',exact:true}).click();
  await page.getByRole('button',{name:'Показать пароль',exact:true}).waitFor();
  assert.equal(await password.getAttribute('type'),'password');
  assert.equal(await password.inputValue(),'demo-only 007 ');
  const theme=await page.evaluate(()=>({accent:getComputedStyle(document.documentElement).getPropertyValue('--accent').trim(),brown:getComputedStyle(document.documentElement).getPropertyValue('--brown').trim()}));
  assert.equal(theme.accent,'#aa4617');assert.equal(theme.brown,'#6c3e28');
  assert.equal(await page.locator('meta[name="theme-color"]').getAttribute('content'),'#fbf6ef');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.getByRole('button',{name:'Показать пароль',exact:true}).isVisible());
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await password.fill('');
  await page.getByLabel('Имя пользователя').fill(env.ADMIN_USERNAME);
  await password.fill(env.ADMIN_PASSWORD);
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  await page.waitForURL('**/products');
  await page.goto((process.env.E2E_BASE_URL??env.APP_ORIGIN)+'/products/14');
  const trigger=page.getByRole('button',{name:'Увеличить фото 1',exact:true});
  await trigger.waitFor();
  await page.setViewportSize({width:1440,height:1000});
  const thumbnail=await trigger.locator('img').boundingBox();
  await trigger.click();
  const dialog=page.locator('dialog.product-image-viewer');
  await dialog.waitFor({state:'visible'});
  await page.waitForFunction(()=>{const image=document.querySelector('.image-viewer-image');return image?.complete&&image.naturalWidth>0;});
  const enlarged=await dialog.locator('img').boundingBox();
  assert.ok(enlarged.height>thumbnail.height*1.5,'Selected image must be larger');
  assert.equal(await page.evaluate(()=>getComputedStyle(document.body).overflow),'hidden');
  await page.screenshot({path:resolve(output,'image-viewer-warm.png'),fullPage:false});
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(()=>Boolean(document.activeElement?.closest('dialog'))),true,'Focus stays in modal');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(()=>Boolean(document.activeElement?.closest('dialog'))),true,'Reverse focus stays in modal');
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  assert.equal(await trigger.evaluate(element=>document.activeElement===element),true,'Focus returns to photo');
  assert.notEqual(await page.evaluate(()=>getComputedStyle(document.body).overflow),'hidden');
  await trigger.click();await dialog.waitFor({state:'visible'});
  await page.getByRole('button',{name:'Закрыть фото',exact:true}).click();await dialog.waitFor({state:'hidden'});
  await trigger.click();await dialog.waitFor({state:'visible'});await page.mouse.click(2,2);await dialog.waitFor({state:'hidden'});
  await page.setViewportSize({width:390,height:844});await trigger.click();await dialog.waitFor({state:'visible'});
  await page.waitForFunction(()=>{const image=document.querySelector('.image-viewer-image');return image?.complete&&image.naturalWidth>0;});
  assert.ok(await dialog.evaluate(element=>{const r=element.getBoundingClientRect();return r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight;}),'Mobile viewer stays in viewport');
  await page.screenshot({path:resolve(output,'image-viewer-mobile.png'),fullPage:false});
  await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
  console.log('UI enhancements passed: password show/hide preserves value, warm global theme, enlarged photo, focus/scroll, Escape/button/backdrop closing, mobile viewport; no browser errors.');
} finally {await browser.close();}
