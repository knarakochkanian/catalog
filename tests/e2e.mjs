import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { chromium } from 'playwright';

const here = dirname(fileURLToPath(import.meta.url));
const env = Object.fromEntries((await readFile(resolve(here, '../.env'), 'utf8')).split('\n').filter(line => /^[A-Z_]+=/.test(line)).map(line => { const index = line.indexOf('='); return [line.slice(0,index),line.slice(index+1)]; }));
const baseURL = process.env.E2E_BASE_URL ?? env.APP_ORIGIN ?? 'http://localhost:8080';
const browser = await chromium.launch(process.env.E2E_CHROMIUM_EXECUTABLE ? {executablePath:process.env.E2E_CHROMIUM_EXECUTABLE} : {});
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage();
const failures = [];
page.on('pageerror', error => failures.push(error.message));
let listRequests = 0;
page.on('request', request => { if (new URL(request.url()).pathname === '/api/products') listRequests++; });
try {
  await page.goto('/products');
  await page.getByLabel('Имя пользователя').fill(process.env.ADMIN_USERNAME ?? env.ADMIN_USERNAME);
  await page.getByLabel('Пароль', { exact: true }).fill(process.env.ADMIN_PASSWORD ?? env.ADMIN_PASSWORD);
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.waitForURL('**/products');
  assert.equal((await context.request.post('/api/imports', { headers: { Origin: baseURL } })).status(), 403, 'CSRF required');
  assert.equal((await context.request.get('/api/products?page=0')).status(), 422, 'Pagination validation');
  assert.equal((await context.request.get('/api/products?min_price=50&max_price=10')).status(), 422, 'Price range validation');
  await page.getByRole('link', { name: /Импорт товаров/ }).first().click();
  await page.locator('#import-file').setInputFiles(resolve(here, '../backend/tests/fixtures/e2e.xlsx'));
  const uploadResponse = page.waitForResponse(response => response.url().endsWith('/api/imports') && response.request().method() === 'POST');
  await page.getByRole('button', { name: /Начать импорт/ }).click();
  const jobResponse = await uploadResponse;
  assert.equal(jobResponse.status(), 202);
  const job = await jobResponse.json();
  if (process.env.E2E_LOCAL_WORKER === '1') execFileSync(process.env.E2E_PHP_BIN ?? 'php', [resolve(here,'process-job.php'),job.id], { env: process.env, stdio:'pipe', timeout:20000 });
  await page.getByRole('heading', { name: 'Импорт завершён', exact:true }).waitFor({ timeout:30000 });
  const report = await (await context.request.get(`/api/imports/${job.id}`)).json();
  assert.equal(report.processed, 3); assert.equal(report.skipped, 1); assert.equal(report.errors[0].row,4);
  assert.equal(report.created + report.updated, 2);
  await page.getByRole('link', { name: /Открыть каталог/ }).click();
  await page.locator('#search').fill('E2E товар');
  await page.getByText('E2E товар 001', { exact:true }).waitFor();
  const requestsBefore = listRequests;
  await page.locator('#search').fill('E2E товар');
  await page.waitForTimeout(600);
  assert.equal(listRequests, requestsBefore, 'Repeated identical filter must not fetch again');
  await page.getByText('E2E товар 001', { exact:true }).click();
  await page.getByRole('heading', { name:'E2E товар 001',exact:true }).waitFor();
  await page.getByText('000001', { exact:true }).waitFor();
  await page.getByText('0', { exact:true }).waitFor();
  await page.getByRole('link', { name: /К списку товаров/ }).click();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name:'Экспорт XLSX',exact:true }).click();
  const download = await downloadEvent;
  assert.equal(download.suggestedFilename(),'products.xlsx');
  const artifacts = process.env.E2E_OUTPUT_DIR ?? resolve(here, '../backend/var/e2e');
  await mkdir(artifacts, { recursive:true });
  const exportPath=resolve(artifacts,'products.xlsx');await download.saveAs(exportPath);
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(100);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile must not overflow');
  await page.screenshot({path:resolve(artifacts,'mobile.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:resolve(artifacts,'catalog.png'),fullPage:true});
  await page.getByRole('link', { name:/Импорт товаров/ }).first().click();
  await page.locator('#import-file').setInputFiles(exportPath);
  const reupload=page.waitForResponse(response=>response.url().endsWith('/api/imports')&&response.request().method()==='POST');
  await page.getByRole('button',{name:/Начать импорт/}).click();
  const repeated=await (await reupload).json();
  if(process.env.E2E_LOCAL_WORKER==='1') execFileSync(process.env.E2E_PHP_BIN??'php',[resolve(here,'process-job.php'),repeated.id],{env:process.env,stdio:'pipe',timeout:20000});
  await page.getByRole('heading',{name:'Импорт завершён',exact:true}).waitFor({timeout:30000});
  const repeatReport=await(await context.request.get(`/api/imports/${repeated.id}`)).json();
  assert.equal(repeatReport.created,0);assert.equal(repeatReport.updated,2);assert.equal(repeatReport.skipped,0);
  assert.deepEqual(failures,[],'No uncaught browser errors');
  await page.getByRole('button',{name:'Выйти',exact:true}).click();
  await page.waitForURL('**/login');
  console.log('E2E passed: login, CSRF, validation, async import/report, list/filter dedupe, detail, export/reimport, responsive layout, logout; no browser errors.');
} finally { await browser.close(); }
